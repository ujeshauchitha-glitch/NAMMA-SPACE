#!/usr/bin/env python3
"""Navigation grid authoring tool.

Reads geometry bounds from a geometry-report.json (output of process_geometry.py
or ply_to_glb.py run with --report) and generates a nav-data.json occupancy grid
compatible with the Namma Space NavigationSchema (src/types/scene.ts).

Schema output format (matching NavigationSchema in scene.ts):
  {
    "version": 1,
    "coordinateSystem": "x-z-grid",
    "origin": { "x": ..., "z": ... },
    "cellSize": 0.25,
    "width": ...,   (number of columns, X direction)
    "height": ...,  (number of rows, Z direction)
    "blocked": [...],    (flat 1D indices: row * width + col, for obstacle cells)
    "unknown": [],
    "start": { "x": ..., "z": ... },    (col, row of player start — must be walkable)
    "clearanceMetres": 0.3
  }

Usage (non-interactive scaffold):
    python scripts/make_nav_grid.py \\
        --geometry-report ./geometry-out/geometry-report.json \\
        --output ./nav-out/nav-data.json \\
        --no-interactive

Usage (interactive obstacle marking):
    python scripts/make_nav_grid.py \\
        --geometry-report ./geometry-out/geometry-report.json \\
        --output ./nav-out/nav-data.json

Usage (manual bounds, no geometry-report):
    python scripts/make_nav_grid.py \\
        --bounds -5 0 -4 5 3 4 \\
        --output ./nav-out/nav-data.json \\
        --no-interactive

The all-walkable scaffold MUST be edited to mark obstacle cells before publishing.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path


def load_bounds_from_report(report_path: Path) -> tuple[list[float], list[float]]:
    """Extract min/max bounds from a geometry-report.json."""
    data = json.loads(report_path.read_text(encoding="utf-8"))
    bounds = data.get("bounds")
    if not isinstance(bounds, dict):
        raise ValueError("geometry-report.json does not contain a 'bounds' key.")
    minimum = bounds.get("min")
    maximum = bounds.get("max")
    if not isinstance(minimum, list) or not isinstance(maximum, list) or len(minimum) < 3 or len(maximum) < 3:
        raise ValueError("bounds.min and bounds.max must be 3-element lists in [x, y, z] order.")
    return [float(v) for v in minimum], [float(v) for v in maximum]


def world_to_index(ox: float, oz: float, cell_size: float, width: int, wx: float, wz: float) -> int:
    """Convert world XZ coordinates to a flat cell index (row * width + col)."""
    col = int((wx - ox) / cell_size)
    row = int((wz - oz) / cell_size)
    col = max(0, min(width - 1, col))
    return col, row


def build_nav_data(
    minimum: list[float],
    maximum: list[float],
    cell_size: float,
    clearance: float,
) -> dict:
    """Build an all-walkable nav-data dict from world-space bounds."""
    origin_x = minimum[0]
    origin_z = minimum[2]
    extent_x = maximum[0] - minimum[0]
    extent_z = maximum[2] - minimum[2]
    width = max(1, math.ceil(extent_x / cell_size))
    height = max(1, math.ceil(extent_z / cell_size))

    return {
        "version": 1,
        "coordinateSystem": "x-z-grid",
        "origin": {"x": round(origin_x, 6), "z": round(origin_z, 6)},
        "cellSize": cell_size,
        "width": width,
        "height": height,
        "blocked": [],       # All cells walkable by default
        "unknown": [],
        "start": {"x": width // 2, "z": height // 2},
        "clearanceMetres": clearance,
        "_notes": [
            "'blocked' is a list of flat 1D indices: row * width + col.",
            "Mark wall, furniture, and column cells in 'blocked' before publishing.",
            "'start' must be a verified walkable cell (not in blocked or unknown).",
            "Generated by make_nav_grid.py from geometry bounds.",
        ],
    }


def rect_world_to_indices(
    ox: float, oz: float, cell_size: float, width: int, height: int,
    wx_min: float, wz_min: float, wx_max: float, wz_max: float,
) -> list[int]:
    """Convert a world-space XZ rectangle to a list of flat cell indices."""
    col_min = max(0, int((wx_min - ox) / cell_size))
    col_max = min(width, int(math.ceil((wx_max - ox) / cell_size)))
    row_min = max(0, int((wz_min - oz) / cell_size))
    row_max = min(height, int(math.ceil((wz_max - oz) / cell_size)))
    indices = []
    for row in range(row_min, row_max):
        for col in range(col_min, col_max):
            indices.append(row * width + col)
    return indices


def prompt_obstacles_interactive(nav: dict) -> dict:
    """Simple interactive session to mark rectangular obstacle regions."""
    width: int = nav["width"]
    height: int = nav["height"]
    cell_size: float = nav["cellSize"]
    ox: float = nav["origin"]["x"]
    oz: float = nav["origin"]["z"]

    print(f"\nGrid: {width} cols (X) x {height} rows (Z), cell size {cell_size}m")
    print(f"World X range: {ox:.2f} to {ox + width * cell_size:.2f}")
    print(f"World Z range: {oz:.2f} to {oz + height * cell_size:.2f}")
    print("\nMark rectangular obstacle regions (walls, furniture, columns) in WORLD XZ coordinates.")
    print("Format: x_min z_min x_max z_max  (space-separated, metres)")
    print("Enter 'done' to finish. Enter 'skip' to save an all-walkable scaffold.")
    print()

    blocked_set: set[int] = set(nav["blocked"])

    while True:
        try:
            line = input("Obstacle rect (or 'done'/'skip'): ").strip()
        except (KeyboardInterrupt, EOFError):
            print("\nInterrupted.")
            break
        if line.lower() in ("done", ""):
            break
        if line.lower() == "skip":
            print("Saving all-walkable scaffold. Mark obstacles manually in the JSON before publishing.")
            break
        parts = line.split()
        if len(parts) != 4:
            print("  Expected: x_min z_min x_max z_max")
            continue
        try:
            wx_min, wz_min, wx_max, wz_max = (float(p) for p in parts)
        except ValueError:
            print("  Could not parse four numbers.")
            continue
        indices = rect_world_to_indices(ox, oz, cell_size, width, height, wx_min, wz_min, wx_max, wz_max)
        before = len(blocked_set)
        blocked_set.update(indices)
        added = len(blocked_set) - before
        print(f"  Marked {added} new cells as blocked (total blocked: {len(blocked_set)}).")

    # Update start cell
    try:
        start_input = input(
            f"\nStart cell [col row] (default: {nav['start']['x']} {nav['start']['z']}): "
        ).strip()
        if start_input:
            parts = start_input.split()
            if len(parts) == 2:
                sc_col, sc_row = int(parts[0]), int(parts[1])
                start_idx = sc_row * width + sc_col
                if 0 <= sc_col < width and 0 <= sc_row < height:
                    if start_idx in blocked_set:
                        print("  WARNING: Start cell is in blocked list. Clearing this cell from blocked.")
                        blocked_set.discard(start_idx)
                    nav["start"] = {"x": sc_col, "z": sc_row}
                    print(f"  Start cell set to col={sc_col}, row={sc_row}.")
                else:
                    print(f"  Out of bounds (width={width}, height={height}). Keeping default.")
    except (KeyboardInterrupt, EOFError):
        pass

    nav["blocked"] = sorted(blocked_set)
    return nav


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--geometry-report", type=Path,
                        help="Path to geometry-report.json from process_geometry.py.")
    parser.add_argument("--output", type=Path, required=True,
                        help="Output path for nav-data.json.")
    parser.add_argument("--cell-size", type=float, default=0.25,
                        help="Grid cell size in metres (default: 0.25).")
    parser.add_argument("--clearance", type=float, default=0.3,
                        help="Agent clearance radius in metres (default: 0.3).")
    parser.add_argument("--no-interactive", action="store_true",
                        help="Skip interactive obstacle entry; save an all-walkable scaffold.")
    parser.add_argument("--bounds", nargs=6, type=float,
                        metavar=("XMIN", "YMIN", "ZMIN", "XMAX", "YMAX", "ZMAX"),
                        help="Override or supply bounds directly instead of reading from geometry-report.")
    args = parser.parse_args()

    if args.cell_size <= 0:
        print("ERROR: --cell-size must be > 0", file=sys.stderr)
        return 2

    if args.clearance < 0:
        print("ERROR: --clearance must be >= 0", file=sys.stderr)
        return 2

    # Resolve bounds
    if args.bounds:
        minimum = [args.bounds[0], args.bounds[1], args.bounds[2]]
        maximum = [args.bounds[3], args.bounds[4], args.bounds[5]]
        print(f"Using provided bounds: min={minimum}, max={maximum}")
    elif args.geometry_report:
        if not args.geometry_report.is_file():
            print(f"ERROR: geometry-report not found: {args.geometry_report}", file=sys.stderr)
            print("Tip: run process_geometry.py first, or use --bounds XMIN YMIN ZMIN XMAX YMAX ZMAX", file=sys.stderr)
            return 2
        try:
            minimum, maximum = load_bounds_from_report(args.geometry_report)
            print(f"Loaded bounds from {args.geometry_report}")
            print(f"  min={minimum}  max={maximum}")
        except (ValueError, json.JSONDecodeError, OSError) as err:
            print(f"ERROR: {err}", file=sys.stderr)
            return 1
    else:
        print("ERROR: Provide --geometry-report or --bounds", file=sys.stderr)
        return 2

    nav = build_nav_data(minimum, maximum, args.cell_size, args.clearance)
    width, height = nav["width"], nav["height"]
    total_cells = width * height
    print(f"Grid: {width} cols x {height} rows = {total_cells} cells, cell_size={args.cell_size}m")

    if not args.no_interactive:
        nav = prompt_obstacles_interactive(nav)

    obstacle_count = len(nav["blocked"])
    walkable_count = total_cells - obstacle_count
    print(f"\nSummary: {walkable_count}/{total_cells} walkable, {obstacle_count} blocked")

    # Validate start cell
    start_x, start_z = nav["start"]["x"], nav["start"]["z"]
    start_idx = start_z * width + start_x
    if start_idx in set(nav["blocked"]):
        print("WARNING: Start cell is in the blocked list. This will fail Zod validation.", file=sys.stderr)
        print("  Fix: either move the start cell or remove it from blocked.", file=sys.stderr)

    if walkable_count == 0:
        print("WARNING: All cells are blocked. Navigation will be impossible.", file=sys.stderr)

    if obstacle_count == 0 and not args.no_interactive:
        print("NOTE: No obstacles marked. Add wall/furniture cells to 'blocked' in the JSON before publishing.")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(nav, indent=2) + "\n", encoding="utf-8")
    print(f"\nSaved nav-data.json -> {args.output}")
    print("\nNext steps:")
    print("  1. Open the JSON and add flat indices to 'blocked' for walls and furniture.")
    print(f"     Index formula: row * {width} + col  (both 0-based)")
    print("  2. Confirm 'start' is a walkable cell (not in 'blocked' or 'unknown').")
    print("  3. Pass this file to generate_scene_bundle.py --navigation")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
